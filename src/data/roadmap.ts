/**
 * The Cortex learning roadmap: the SYLLABUS DATA, separated from its rendering.
 *
 * Lives in `src/data/` rather than inside the landing page so the same
 * declaration can feed both consumers:
 *
 *   - `src/pages/index.astro`      draws the graph and resolves the links.
 *   - `scripts/audit-syllabus.ts`  reports mapping coverage and gaps.
 *
 * A standalone script cannot reach into an Astro component's frontmatter, so
 * keeping the data here is what makes the roadmap auditable at all.
 *
 * SOURCE: every track and concept list is derived from the CampusX Data Science
 * Mentorship Program (DSMP 2.0) curriculum. Main-track entries mirror the
 * program's subject areas (roughly two weeks of study each); branch entries
 * mirror its individual sessions; concept lists mirror that session's bullets.
 *
 * Concept bullets are matched to note headings AUTOMATICALLY by
 * `src/lib/syllabus/match.ts`, so adding a note requires no edit here. The
 * `{ label, at }` form exists only to override the matcher where it is wrong.
 */
/**
 * One syllabus bullet.
 *
 *   - A bare string is the normal case: `src/lib/syllabus/match.ts` places it in
 *     a note section on its own, using the data-science vocabulary to bridge
 *     differing wording. Nothing to maintain as notes are added.
 *   - The object form is an ESCAPE HATCH for the rare bullet the matcher gets
 *     wrong or cannot place: `at` is matched instead of `label`. A stale `at`
 *     that matches nothing is reported during the build.
 */
export type Concept = string | { label: string; at: string };

export const conceptLabel = (c: Concept): string => (typeof c === 'string' ? c : c.label);

/**
 * How essential a topic is to becoming employable as a data scientist.
 *
 *   'core'     Skip it and later topics break. Every interview assumes it, and
 *              most day-to-day work uses it. This is the default, so the graph
 *              stays calm: only the exceptions are marked.
 *   'advanced' Worth learning, but not a prerequisite for anything downstream.
 *              Either it is specialist (t-SNE, GMM, Apriori), a
 *              nice-to-have tool (Plotly/Dash, tkinter), or depth that a first
 *              pass can defer (SVM kernel maths, boosting variants). A reader
 *              short on time can postpone these and still finish the roadmap.
 *
 * This is an editorial judgement, deliberately recorded as data so it can be
 * argued with and revised in one place rather than being implied by ordering.
 */
export type Tier = 'core' | 'advanced';

/**
 * How hard the MATERIAL is, a separate axis from `Tier` (which is about
 * employability). A topic can be `core` and `advanced` difficulty at once, so
 * this has its own scale and marker (never reuses the amber tier marker).
 */
export type Difficulty = 'beginner' | 'intermediate' | 'advanced';

/** A branch sub-topic with its own concept syllabus. */
export interface Topic {
  label: string;
  /**
   * Note or category Display_Name to link to, when it differs from `label`.
   * Omitted means "resolve by my own label", which is why a new note whose name
   * matches a node lights up with no edit here.
   */
  match?: string;
  /** Defaults to 'core'; only `'advanced'` is ever written out. */
  tier?: Tier;
  /** Optional material difficulty; shown as a colour stripe + modal badge. */
  difficulty?: Difficulty;
  /** Optional prerequisites: labels of topics to learn first (linked if known). */
  prerequisites?: string[];
  concepts: Concept[];
}
/** A main-track step: spine node + its concept syllabus + branch sub-topics. */
export interface Step {
  label: string;
  match?: string;
  /** Defaults to 'core'. A track is advanced only if all of it can be deferred. */
  tier?: Tier;
  /** Optional material difficulty; shown as a colour stripe + modal badge. */
  difficulty?: Difficulty;
  /** Optional prerequisites: labels of topics to learn first (linked if known). */
  prerequisites?: string[];
  concepts: Concept[];
  left?: Topic[];
  right?: Topic[];
}

